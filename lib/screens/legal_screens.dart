/// Push this to show the Terms of Use / Privacy Policy.
/// [initialTab]: 0 = Terms of Use, 1 = Privacy Policy.
class TermsPrivacyScreen extends StatefulWidget {
  final int initialTab;

  const TermsPrivacyScreen({super.key, this.initialTab = 0});

  @override
  State<TermsPrivacyScreen> createState() => _TermsPrivacyScreenState();
}

class _TermsPrivacyScreenState extends State<TermsPrivacyScreen>
    with SingleTickerProviderStateMixin {
  late final TabController _tabController;

  @override
  void initState() {
    super.initState();
    _tabController = TabController(
      length: 2,
      vsync: this,
      initialIndex: widget.initialTab,
    );
  }

  @override
  void dispose() {
    _tabController.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: AppColors.background,
      appBar: AppBar(
        title: const Text('Terms & Privacy'),
        bottom: TabBar(
          controller: _tabController,
          labelColor: AppColors.primary,
          unselectedLabelColor: AppColors.textSecondary,
          indicatorColor: AppColors.primary,
          tabs: const [
            Tab(text: 'Terms of Use'),
            Tab(text: 'Privacy Policy'),
          ],
        ),
      ),
      body: SafeArea(
        top: false,
        child: TabBarView(
          controller: _tabController,
          children: const [
            _LegalDocView(text: LegalContent.termsOfUse),
            _LegalDocView(text: LegalContent.privacyPolicy),
          ],
        ),
      ),
    );
  }
}

class _LegalDocView extends StatelessWidget {
  final String text;
  const _LegalDocView({required this.text});

  @override
  Widget build(BuildContext context) {
    return SingleChildScrollView(
      padding: const EdgeInsets.fromLTRB(20, 20, 20, 32),
      child: Text(
        text.trim(),
        style: const TextStyle(
          fontSize: 13.5,
          height: 1.6,
          color: AppColors.textPrimary,
        ),
      ),
    );
  }
}
